// Command vecgen generates the cross-language parity vectors used by the C#
// test suite: calendar tables, QR payloads, and scenario transcripts (the
// bundled examples plus randomized scripts that exercise every rule).
//
// Usage, from the repository root, with the Go module cloned next to it:
//
//	go -C tools/vecgen run . > tests/PixAutomatico.Tests/Parity/GoVectors.g.cs
package main

import (
	"bytes"
	"fmt"
	"math/rand"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/victorcondackdev/pix-automatico-go/brcode"
	"github.com/victorcondackdev/pix-automatico-go/calendar"
	"github.com/victorcondackdev/pix-automatico-go/scenario"
)

var rng = rand.New(rand.NewSource(20261127))

// lit renders s as a C# verbatim string literal.
func lit(s string) string { return `@"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

func q(s string) string { return strconv.Quote(s) }

var periods = []calendar.Periodicity{calendar.Weekly, calendar.Monthly, calendar.Quarterly, calendar.Semiannual, calendar.Annual}

func main() {
	var o bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&o, f, a...) }
	p("// <auto-generated>\n// Generated by tools/vecgen from the Go implementation (github.com/victorcondackdev/pix-automatico-go).\n")
	p("// Do not edit by hand; regenerate with: go -C tools/vecgen run . > tests/PixAutomatico.Tests/Parity/GoVectors.g.cs\n// </auto-generated>\n\n")
	p("namespace PixAutomatico.Tests.Parity;\n\ninternal static class GoVectors\n{\n")

	// Holidays 2020-2040.
	var n calendar.National
	p("    public static readonly (string Date, string Name)[] Holidays =\n    {\n")
	for d := calendar.MustParse("2020-01-01"); d.Before(calendar.MustParse("2041-01-01")); d = d.AddDays(1) {
		if name := n.Name(d); name != "" {
			p("        (%q, %s),\n", d.String(), q(name))
		}
	}
	p("    };\n\n")

	p("    public static readonly (string Start, string Periodicity, int K, string CycleStart, string DueAdjusted, int CycleOfDue)[] Cycles =\n    {\n")
	for i := 0; i < 150; i++ {
		start := calendar.MustParse("2024-01-01").AddDays(rng.Intn(2500))
		per := periods[rng.Intn(len(periods))]
		k := rng.Intn(40)
		cs := calendar.CycleStart(start, per, k)
		due := calendar.DueDate(n, start, per, k, true)
		p("        (%q, %q, %d, %q, %q, %d),\n", start.String(), string(per), k, cs.String(), due.String(), calendar.CycleOf(start, per, due))
	}
	p("    };\n\n")

	p("    public static readonly (string Name, string City, string RecUrl, string CobUrl, string Amount, string Payload)[] QrCodes =\n    {\n")
	for i := 0; i < 20; i++ {
		pl := brcode.Payload{MerchantName: []string{"Fulano de Tal", "Academia Forte", "Energia Rio SA", "Escola Viva"}[i%4],
			MerchantCity: []string{"BRASILIA", "RIO DE JANEIRO", "NITEROI", "SAO PAULO"}[rng.Intn(4)],
			RecURL:       fmt.Sprintf("pix.example.com/qr/v2/rec/%032x", rng.Uint64())}
		if i%2 == 1 {
			pl.CobURL = fmt.Sprintf("pix.example.com/qr/v2/cob/%016x", rng.Uint64())
			pl.Amount = fmt.Sprintf("%d.%02d", rng.Intn(1000), rng.Intn(100))
		}
		s, err := pl.Encode()
		if err != nil {
			panic(err)
		}
		p("        (%q, %q, %q, %q, %q, %q),\n", pl.MerchantName, pl.MerchantCity, pl.RecURL, pl.CobURL, pl.Amount, s)
	}
	p("    };\n\n")

	p("    public static readonly (string Name, string Script, string Transcript)[] Scenarios =\n    {\n")
	ex := scenario.Examples()
	for _, name := range scenario.ExampleNames() {
		out, err := scenario.Run(ex[name])
		if err != nil {
			panic(err)
		}
		p("        (%q, %s, %s),\n", name, lit(ex[name]), lit(out))
	}
	for i := 0; i < 40; i++ {
		script := randomScript()
		out, err := scenario.Run(script)
		if err != nil {
			panic(fmt.Sprintf("%v\n%s", err, script))
		}
		p("        (%q, %s, %s),\n", fmt.Sprintf("random-%02d", i), lit(script), lit(out))
	}
	p("    };\n}\n")
	os.Stdout.Write(o.Bytes())
}

// randomScript builds a valid script by appending random commands and
// running the prefix to learn which names exist.
func randomScript() string {
	t0 := calendar.MustParse("2026-01-01").AddDays(rng.Intn(365)).At(rng.Intn(24), 0, calendar.BRT)
	lines := []string{"clock " + t0.Format("2006-01-02T15:04")}
	docs := []string{"12345678909", "98765432100", "11222333000181"}
	for _, d := range docs {
		lines = append(lines, fmt.Sprintf("account %s %d.%02d %s", d, rng.Intn(120), rng.Intn(100), []string{"0", "0", "300.00"}[rng.Intn(3)]))
	}
	now := t0
	var recs, solics, charges []string
	money := func() string { return fmt.Sprintf("%d.%02d", 5+rng.Intn(400), rng.Intn(100)) }
	date := func(lo, hi int) string { return calendar.FromTime(now).AddDays(lo + rng.Intn(hi-lo+1)).String() }
	pick := func(s []string) string { return s[rng.Intn(len(s))] }
	for step := 0; step < 70; step++ {
		var cmd string
		switch r := rng.Intn(100); {
		case r < 10 || len(recs) == 0:
			name := fmt.Sprintf("r%d", step)
			val := ""
			if rng.Intn(2) == 0 {
				val = " valor=" + money()
			} else if rng.Intn(2) == 0 {
				val = " piso=" + money()
			}
			end := ""
			if rng.Intn(4) == 0 {
				end = " fim=" + date(40, 400)
			}
			cmd = fmt.Sprintf("rec %s contrato=C%d objeto=Plano_%d devedor=%s nome=Cliente_%d recebedor=Loja_%d inicio=%s periodicidade=%s%s%s retentativa=%s ajuste=%s jornada=%d",
				name, rng.Intn(6), step, pick(docs), step, rng.Intn(3), date(-1, 12), periods[rng.Intn(5)], val, end,
				[]string{"NAO_PERMITE", "PERMITE_3R_7D", "PERMITE_3R_7D"}[rng.Intn(3)], []string{"sim", "nao"}[rng.Intn(2)], 1+rng.Intn(4))
			recs = append(recs, name)
		case r < 24:
			opts := ""
			if rng.Intn(2) == 0 {
				opts += " max=" + money()
			}
			if rng.Intn(3) == 0 {
				opts += " imediato=" + money()
			}
			cmd = "approve " + pick(recs) + opts
		case r < 27:
			name := fmt.Sprintf("s%d", step)
			cmd = fmt.Sprintf("solicit %s %s %s", pick(recs), name, now.Add(time.Duration(1+rng.Intn(24*35))*time.Hour).Format("2006-01-02T15:04"))
			solics = append(solics, name)
		case r < 29 && len(solics) > 0:
			cmd = "cancelsolic " + pick(solics)
		case r < 31:
			cmd = "reject " + pick(recs)
		case r < 33:
			cmd = "revise " + pick(recs) + " " + date(-1, 30)
		case r < 36:
			cmd = "max " + pick(recs) + " " + []string{"0", money()}[rng.Intn(2)]
		case r < 39:
			cmd = fmt.Sprintf("cancelrec %s %s motivo_%d", pick(recs), []string{"PAGADOR", "RECEBEDOR"}[rng.Intn(2)], step)
		case r < 58:
			name := fmt.Sprintf("c%d", step)
			due := date(2, 10)
			if rng.Intn(5) == 0 {
				due = date(0, 13)
			}
			cmd = fmt.Sprintf("charge %s %s %s %s", name, pick(recs), due, money())
			charges = append(charges, name)
		case r < 68 && len(charges) > 0:
			cmd = fmt.Sprintf("retry %s %s", pick(charges), date(-1, 9))
		case r < 70 && len(charges) > 0:
			cmd = fmt.Sprintf("cancelcharge %s %s", pick(charges), []string{"PAGADOR", "RECEBEDOR"}[rng.Intn(2)])
		case r < 76:
			cmd = fmt.Sprintf("deposit %s %s", pick(docs), money())
		case r < 80 && (len(charges) > 0):
			cmd = "status " + pick(append(append([]string{}, recs...), charges...))
		default:
			now = now.Add(time.Duration(1+rng.Intn(24*6)) * time.Hour)
			cmd = "advance " + now.Format("2006-01-02T15:04")
		}
		trial := append(append([]string{}, lines...), cmd)
		out, err := scenario.Run(strings.Join(trial, "\n"))
		if err != nil {
			// Undo bookkeeping for a name whose creation would not exist.
			continue
		}
		last := out[strings.LastIndex(out, "> "+cmd):]
		created := strings.HasPrefix(strings.SplitN(last, "\n", 3)[1], "  ok")
		if !created {
			switch {
			case strings.HasPrefix(cmd, "rec "):
				recs = recs[:len(recs)-1]
			case strings.HasPrefix(cmd, "solicit "):
				solics = solics[:len(solics)-1]
			case strings.HasPrefix(cmd, "charge "):
				charges = charges[:len(charges)-1]
			}
		}
		lines = trial
	}
	lines = append(lines, "advance "+now.Add(30*24*time.Hour).Format("2006-01-02T15:04"))
	return strings.Join(lines, "\n") + "\n"
}
